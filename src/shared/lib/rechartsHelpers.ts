// Recharts типизирует onClick-обработчики Bar/Pie слишком строго под
// generic-props самого компонента, а не под наши данные — практический
// способ обойти это, не теряя типизацию исходных данных, один общий
// хелпер вместо `as any` в каждом графике.
export function barPayload<T>(entry: unknown): T {
  return (entry as { payload: T }).payload
}

// Единые параметры категориальной оси X для всех графиков "Обзора".
// Одинаковые для всех — намеренно: если у соседних карточек в сетке разная
// высота, отведённая под подписи оси X, отличается и высота самой области
// графика (а значит "плывут" линия оси X и сетка по Y между соседними
// диаграммами). interval=0 обязателен отдельно от этого — без него Recharts
// сам решает, какие подписи пропустить при недостатке места, и при
// некоторых ширинах экрана произвольно теряет отдельные месяцы/категории.
export const CATEGORY_X_AXIS_PROPS = {
  interval: 0 as const,
  angle: -20,
  textAnchor: 'end' as const,
  height: 60,
  fontSize: 11,
}
